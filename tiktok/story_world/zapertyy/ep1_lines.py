def path(i):
    return os.path.join(OUT, f"{i}.mp3")


if __name__ == "__main__":
    import eleven
    os.makedirs(OUT, exist_ok=True)
    need = [ln for ln in LINES if not os.path.exists(path(ln[0]))]
    print("символов:", sum(len(t) for _, _, t, _ in need), "осталось на счету:", eleven.balance())
    for i, _, text, kw in need:
        args = dict(stability=0.45, similarity=0.8, style=0.15, speed=0.95)
        args.update(kw)
